create database ROUTE;
USE ROUTE;
CREATE TABLE STUDENTS (
STUDENT_ID int,
STUDENT_NAME varchar(50),
COURSE varchar(30),
CITY varchar(30),
COURSE_FEE decimal(10,2),
JOINED_DATE DATE
);
SELECT * FROM STUDENTS;
describe STUDENTS;
